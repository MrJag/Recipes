import fs from "node:fs";
import assert from "node:assert/strict";
let checks = 0;
const check=(condition,description)=>{assert.ok(condition,description);checks++;};
const read=(path)=>fs.readFileSync(path,"utf8");
const html=read("index.html");
const legacy=read("index2.html");
const script=read("src/scripts/cookbook.js");
const directory=read("src/scripts/category-index.js");
const taxonomy=JSON.parse(read("src/data/recipe-taxonomy.json"));
const css=read("src/styles/cookbook.css");
const refs=[...html.matchAll(/data-recipe="([^"]+)"/g)].map(m=>m[1]).filter(p=>p.startsWith("recipes/") && p.endsWith(".json"));
const assigned=taxonomy.groups.flatMap(g=>g.subcategories.flatMap(s=>s.slugs));
check(refs.length>100,"Recipe catalog must be present on homepage");
check(refs.length===assigned.length,"Taxonomy must match the recipe catalog");
check(new Set(assigned).size===assigned.length,"Taxonomy must not duplicate recipes");
check(html.includes('id="recipeView"')&&html.includes('id="pages"'),"Recipe print/viewer must live on homepage");
check(html.includes('id="recipeIndex" hidden'),"Legacy cuisine list must be data-only");
check(!html.includes("index2.html?recipe="),"Homepage must use canonical recipe links");
check(!html.includes('class="index-link"'),"No redundant All recipes link");
check(directory.includes('new URL("./index.html", location.href)'),"Directory reads homepage catalog");
check(legacy.includes('location.replace("./" + location.search + location.hash)'),"Old recipe links redirect");
check(script.includes("recipe-open"),"Router toggles recipe display");
check(/\.sheet:not\(\.has-photo\) \.content/.test(css),"Continuation pages use full width");
check(/index === 0 \? " has-photo"/.test(script),"Photo strip only on first page");
for(const path of refs){
  check(fs.existsSync(path),"Missing recipe: "+path);
  const data=JSON.parse(read(path));
  check(Boolean(data.title)&&Array.isArray(data.steps)&&Array.isArray(data.ingredientGroups),"Invalid recipe: "+path);
  if(data.photo)check(fs.existsSync(data.photo.replace(/^\.\//,"")),"Missing photo: "+data.photo);
}
console.log("PASS: "+checks+" cookbook checks");
